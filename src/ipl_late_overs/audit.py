"""Stage: audit. Write reports/data_audit.md describing what the raw data contains.

Reads the parsed tables plus the raw zip (for format-level checks that the tables
don't keep, e.g. which JSON keys appear in which season). Read-only: changes nothing.
"""

from __future__ import annotations

import json
import logging
import zipfile
from collections import Counter, defaultdict
from pathlib import Path

import pandas as pd

from . import config, schemas
from .parse import OUTPUTS

log = logging.getLogger(__name__)


def md_table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |")
    return "\n".join(lines)


def load_tables() -> dict[str, pd.DataFrame]:
    return {name: schemas.read_table(config.path(name), schema) for name, schema in OUTPUTS.items()}


def raw_format_by_season(zip_path: Path, season_of: dict[str, int]) -> pd.DataFrame:
    """Share of matches per season in which each optional JSON feature appears."""
    feats: dict[int, Counter] = defaultdict(Counter)
    with zipfile.ZipFile(zip_path) as zf:
        for name in zf.namelist():
            if not name.endswith(".json"):
                continue
            j = json.loads(zf.read(name))
            info, s = j["info"], season_of[Path(name).stem]
            seen = set()
            if any(len(p) > 11 for p in info["players"].values()):
                seen.add(">11 players per team")
            for k in ("city", "player_of_match"):
                if k not in info:
                    seen.add(f"info.{k} missing")
            for inn in j.get("innings", []):
                if inn.get("super_over"):
                    continue
                if "powerplays" not in inn:
                    seen.add("innings.powerplays missing")
                for k in ("miscounted_overs", "absent_hurt"):
                    if k in inn:
                        seen.add(f"innings.{k}")
                for ov in inn.get("overs", []):
                    for d in ov["deliveries"]:
                        if "review" in d:
                            seen.add("delivery.review")
                        if "actual_delivery" not in d:
                            seen.add("delivery.actual_delivery missing")
                        for kind in d.get("replacements", {}):
                            seen.add(f"replacements.{kind}")
            feats[s].update(seen)
    df = pd.DataFrame(feats).T.fillna(0).astype(int).sort_index()
    return df[sorted(df.columns)]


def over_anomalies(d: pd.DataFrame) -> pd.DataFrame:
    """Overs (regular innings) whose legal-ball count isn't 6, excluding each innings' final over."""
    reg = d[~d["is_super_over"]]
    g = reg.groupby(["match_id", "innings", "over"], as_index=False).agg(
        legal=("is_legal", "sum"), n_bowlers=("bowler_id", "nunique")
    )
    last = g.groupby(["match_id", "innings"])["over"].transform("max")
    g["is_last_over"] = g["over"] == last
    return g


def innings_totals(d: pd.DataFrame) -> pd.DataFrame:
    return (
        d[~d["is_super_over"]]
        .groupby(["match_id", "innings", "batting_team"], as_index=False)
        .agg(
            runs=("runs_total", "sum"),
            wickets=("n_wickets", "sum"),
            legal_balls=("is_legal", "sum"),
            last_over=("over", "max"),
        )
    )


def build_report(t: dict[str, pd.DataFrame], zip_path: Path) -> str:
    cfg = config.load_config()
    m, d, mp, people, rep = t["matches"], t["deliveries"], t["match_players"], t["people"], t["replacements"]
    manifest = schemas.read_json(config.path("download_manifest"), schemas.DOWNLOAD_MANIFEST_KEYS)
    out: list[str] = []
    w = out.append

    w("# Data audit\n")
    w("_Generated by `make audit` (src/ipl_late_overs/audit.py). Do not edit by hand._\n")

    # ------------------------------------------------------------------ provenance
    w("## 1. Source\n")
    w(f"- URL: {manifest['url']}")
    w(f"- File: `data/raw/{manifest['file']}` ({manifest['size_bytes']:,} bytes)")
    w(f"- SHA-256: `{manifest['sha256']}`")
    w(f"- Downloaded (UTC): {manifest['downloaded_at_utc']} ({manifest['note']})")
    w(f"- Cricsheet data version(s): {', '.join(sorted(m['data_version'].unique()))}")
    w(f"- Matches: **{len(m):,}**; deliveries: **{len(d):,}**; distinct players: **{len(people):,}**")
    w(f"- Date range: {m['date'].min().date()} to {m['date'].max().date()}\n")

    # ------------------------------------------------------------------ seasons
    w("## 2. Seasons\n")
    w("`season` = calendar year of the first day of play. Cricsheet's labels are kept in "
      "`season_label`; three are split-year labels (2007/08 = 2008, 2009/10 = 2010, 2020/21 = 2020) "
      "and are normalised to the year the matches were actually played. Each label maps to exactly one year (asserted in parse).\n")
    tot = innings_totals(d)
    so_matches = set(m.loc[m["has_super_over"], "match_id"])
    per = m.groupby(["season", "season_label"]).agg(
        matches=("match_id", "size"),
        first=("date", "min"),
        last=("date", "max"),
        no_result=("result", lambda s: int((s == "no result").sum())),
        ties=("result", lambda s: int((s == "tie").sum())),
        dl=("method", lambda s: int(s.notna().sum())),
        target_lt_20=("target_overs", lambda s: int((s < cfg["match"]["overs"]).sum())),
        super_over=("has_super_over", "sum"),
    ).reset_index()
    per["first"] = per["first"].dt.date
    per["last"] = per["last"].dt.date
    w(md_table(per))
    w("")

    # ------------------------------------------------------------------ outcomes
    w("## 3. Match outcomes that matter for exclusions\n")
    w("Nothing is excluded in week 1. These are the candidates the week-2 cleaning stage will act on.\n")
    nr = m[m["result"] == "no result"]
    w(f"### 3.1 No-result matches: {len(nr)}\n")
    n_inn = d[~d["is_super_over"]].groupby("match_id")["innings"].nunique()
    nr_view = nr[["match_id", "date", "team1", "team2"]].assign(
        innings_with_balls=nr["match_id"].map(n_inn).fillna(0).astype(int)
    )
    w(md_table(nr_view.assign(date=nr_view["date"].dt.date)))
    w("")

    revised = m[(m["method"].notna()) | (m["target_overs"] < cfg["match"]["overs"])]
    w(f"### 3.2 D/L or revised-target matches: {len(revised)}\n")
    w(f"- With an outcome method (all `D/L`): {int(m['method'].notna().sum())}")
    w(f"- With second-innings target overs < {cfg['match']['overs']}: {int((m['target_overs'] < cfg['match']['overs']).sum())}")
    w(f"- Target overs < {cfg['match']['overs']} but no method (shortened before play / rain-reduced with no D/L result): "
      f"{int(((m['target_overs'] < cfg['match']['overs']) & m['method'].isna()).sum())}")
    w(f"- Method present but target overs = {cfg['match']['overs']}: "
      f"{int((m['method'].notna() & (m['target_overs'] >= cfg['match']['overs'])).sum())}\n")
    rv = revised[["match_id", "date", "team1", "team2", "method", "target_runs", "target_overs", "result"]]
    w(md_table(rv.assign(date=rv["date"].dt.date).sort_values("date")))
    w("")

    so_inn = d[d["is_super_over"]].groupby("match_id")["innings"].nunique()
    w(f"### 3.3 Super overs: {len(so_matches)} matches, {int(so_inn.sum())} super-over innings\n")
    w(f"Ties without a super over in the data: {int(((m['result'] == 'tie') & ~m['has_super_over']).sum())}. "
      "Super-over deliveries are flagged `is_super_over` and will be excluded from all late-over tables.\n")
    sov = m[m["has_super_over"]][["match_id", "date", "team1", "team2", "eliminator"]]
    w(md_table(sov.assign(date=sov["date"].dt.date, super_over_innings=sov["match_id"].map(so_inn)).sort_values("date")))
    w("")

    one_inn = m[m["n_innings"] < 2]
    w(f"### 3.4 Matches with fewer than two innings: {len(one_inn)}\n")
    w("All are no-results (abandoned during or before the first innings).\n" if set(one_inn["match_id"]) <= set(nr["match_id"]) else "**Not all are no-results: investigate.**\n")

    # ------------------------------------------------------------------ missing fields
    w("## 4. Missing fields\n")
    nulls = pd.DataFrame({"column": m.columns, "nulls": [int(m[c].isna().sum()) for c in m.columns]})
    nulls = nulls[nulls["nulls"] > 0]
    w("Matches table, columns with any nulls (structural nulls such as `win_by_runs` when the chasing side won are expected):\n")
    w(md_table(nulls))
    w("")
    dn = {c: int(d[c].isna().sum()) for c in d.columns if d[c].isna().any()}
    w(f"Deliveries table: only the wicket columns have nulls (they are null on balls without a wicket): {dn}.\n")
    tgt_missing = m[(m["n_innings"] >= 2) & m["target_runs"].isna()]
    w(f"Matches with two innings but no recorded target: {len(tgt_missing)}.\n")

    # ------------------------------------------------------------------ duplicates
    w("## 5. Duplicates\n")
    w(f"- Duplicate match IDs: {int(m['match_id'].duplicated().sum())}")
    pair = m.assign(pair=m[["team1", "team2"]].apply(lambda r: " v ".join(sorted(r)), axis=1))
    dup_fixture = pair[pair.duplicated(["date", "pair"], keep=False)]
    w(f"- Same date + same two teams (possible duplicate matches): {len(dup_fixture)}")
    w(f"- Duplicate delivery keys (match, innings, ball_seq): {int(d.duplicated(['match_id', 'innings', 'ball_seq']).sum())}")
    legal = d[d["is_legal"] & d["actual_delivery"].notna()]
    dup_label = legal[legal.duplicated(["match_id", "innings", "actual_delivery"], keep=False)]
    w(f"- Legal deliveries sharing an `actual_delivery` label within an innings: {len(dup_label)} rows "
      f"in {dup_label[['match_id', 'innings']].drop_duplicates().shape[0]} innings")
    same = d.duplicated([c for c in d.columns if c not in ("ball_seq", "ball_in_over")], keep=False)
    w(f"- Rows identical in every field except their position: {int(same.sum())} (expected: identical dot balls etc. "
      "are legitimate; the `actual_delivery` label check above is the meaningful one)\n")

    # ------------------------------------------------------------------ overs
    w("## 6. Over structure (regular innings)\n")
    g = over_anomalies(d)
    mid_innings = g[~g["is_last_over"]]
    w(f"- Overs: {len(g):,}. Not the innings' last over but legal balls != {cfg['match']['balls_per_over']}: "
      f"**{int((mid_innings['legal'] != cfg['match']['balls_per_over']).sum())}**")
    w(f"- Innings flagged by Cricsheet as `miscounted_overs`: {int(m['has_miscounted_overs'].sum())} matches")
    late = g[(g["over"] >= cfg["late_overs"]["first_over_index"]) & (g["over"] <= cfg["late_overs"]["last_over_index"])]
    w(f"- Overs with more than one bowler (bowler injured / replaced mid-over): {int((g['n_bowlers'] > 1).sum())} "
      f"overall, {int((late['n_bowlers'] > 1).sum())} in overs 15-20")
    w(f"- Over indices outside 0-{cfg['match']['overs'] - 1}: {int(((g['over'] < 0) | (g['over'] >= cfg['match']['overs'])).sum())}")
    gaps = g.groupby(["match_id", "innings"])["over"].agg(lambda s: s.max() + 1 - s.nunique())
    w(f"- Innings with a missing over number in the sequence: {int((gaps > 0).sum())}\n")
    odd = mid_innings[mid_innings["legal"] != cfg["match"]["balls_per_over"]]
    if len(odd):
        w(md_table(odd[["match_id", "innings", "over", "legal"]].sort_values(["match_id", "innings", "over"])))
        w("")

    # ------------------------------------------------------------------ consistency
    w("## 7. Scorecard consistency\n")
    reg_m = m[(m["n_innings"] >= 2) & m["method"].isna() & (m["target_overs"] >= cfg["match"]["overs"])]
    first = tot[tot["innings"] == 1].set_index("match_id")
    second = tot[tot["innings"] == 2].set_index("match_id")
    exp_target = first.loc[reg_m["match_id"], "runs"].values + 1
    bad_target = reg_m[reg_m["target_runs"].values != exp_target]
    w(f"- Unrevised matches where target != first-innings total + 1: **{len(bad_target)}** of {len(reg_m)}")
    chase_won = reg_m[reg_m["win_by_wickets"].notna()]
    short = chase_won[second.loc[chase_won["match_id"], "runs"].values < chase_won["target_runs"].values]
    w(f"- Chases won by wickets where chase total < target: **{len(short)}**")
    bat_won = reg_m[reg_m["win_by_runs"].notna()]
    margin = bat_won["target_runs"].values - 1 - second.loc[bat_won["match_id"], "runs"].values
    w(f"- Wins by runs where margin != target - 1 - chase total: **{int((margin != bat_won['win_by_runs'].values).sum())}**")
    w(f"- Innings with more than 10 wicket entries: {int((tot['wickets'] > 10).sum())}\n")

    # ------------------------------------------------------------------ wickets
    w("## 8. Wicket kinds\n")
    wk = d["wicket_kind"].value_counts().rename_axis("kind").reset_index(name="count")
    w(md_table(wk))
    w("\n`retired hurt` is recorded as a wicket entry but is not a dismissal; `retired out` is. "
      "The week-2 late-over table will count wickets fallen accordingly (rule documented there).\n")

    # ------------------------------------------------------------------ format
    w("## 9. JSON format differences across seasons\n")
    fmt = raw_format_by_season(zip_path, dict(zip(m["match_id"], m["season"])))
    w("Number of matches per season in which each feature appears (regular innings only):\n")
    w(md_table(fmt.reset_index(names="season")))
    w("")
    imp = rep[rep["kind"] == "match"]
    w("Key observations:\n")
    w(f"- **Impact player (from 2023).** `info.players` lists 12 per team (the impact substitute is included) and "
      f"`replacements.match` records {len(imp)} substitutions ({', '.join(f'{k}: {v}' for k, v in imp['reason'].value_counts().items())}). "
      "Squads can therefore exceed 11 (12 from 2023; 13 when a concussion substitute is also used); "
      "squad-based eligibility in week 7 must not assume 11.")
    w(f"- **Mid-over role replacements** (`replacements.role`, e.g. injured bowler): {int((rep['kind'] == 'role').sum())}, spread across all seasons.")
    w("- **`delivery.review`** (DRS) is recorded from 2018 onwards only.")
    w("- **`actual_delivery`** is present on every delivery in this data version.")
    w("- **Two-day matches**: " + ", ".join(m.loc[m["n_dates"] > 1, "match_id"]) + " (reserve-day finishes; `date` = first day).\n")

    # ------------------------------------------------------------------ teams / players
    w("## 10. Teams and players\n")
    teams = pd.concat([m[["season", "team1"]].rename(columns={"team1": "team"}), m[["season", "team2"]].rename(columns={"team2": "team"})])
    tt = teams.groupby("team")["season"].agg(["min", "max", "count"]).reset_index().rename(columns={"min": "first", "max": "last", "count": "matches"})
    w(md_table(tt.sort_values("team")))
    w("\nFranchise renames appear as different names (Delhi Daredevils -> Delhi Capitals, Kings XI Punjab -> Punjab Kings, "
      "Royal Challengers Bangalore -> Bengaluru, Rising Pune Supergiant(s)). Team names are not used as model keys; "
      "if a team feature is added later, a reviewed mapping goes in config.\n")
    multi_name = people[people["all_names"].str.contains(";")]
    w(f"- Players (registry IDs): {len(people):,}. IDs seen under more than one name: {len(multi_name)}.")
    name_ids = mp.groupby("player_name")["player_id"].nunique()
    w(f"- Names shared by more than one registry ID: {int((name_ids > 1).sum())}"
      + (f" ({', '.join(name_ids[name_ids > 1].index)})" if (name_ids > 1).any() else "")
      + ". This is why the player key is the registry ID, never the name.")
    sq = mp.groupby(["match_id", "team"]).size()
    w(f"- Squad sizes per team per match: {dict(sorted((int(k), int(v)) for k, v in Counter(sq.values).items()))}\n")

    # ------------------------------------------------------------------ exclusions
    out.extend(late_over_sections(m, people))

    # ------------------------------------------------------------------ splits
    w("## 13. Season split (`data/processed/splits.json`)\n")
    sp = schemas.read_json(config.path("splits"), schemas.SPLITS_KEYS)
    w(md_table(pd.DataFrame([
        {"split": k, "seasons": f"{v['seasons'][0]}-{v['seasons'][-1]}", "n_seasons": len(v["seasons"]),
         "matches": v["matches"], "late-over rows": v["late_over_rows"]}
        for k, v in ((k, sp["counts"][k]) for k in ("train", "validation", "test"))
    ])))
    w("\nEvery match is in exactly one split and every test match is later than every train/validation "
      "match (asserted in `splits.py`). Folds: `reports/splits.md`.\n")
    return "\n".join(out) + "\n"


def late_over_sections(m: pd.DataFrame, people: pd.DataFrame) -> list[str]:
    """Sections 11-12: the exclusion log and the late-over table (stage: overs)."""
    cfg = config.load_config()
    excl = schemas.read_json(config.path("overs_exclusions"), schemas.OVERS_EXCLUSIONS_KEYS)
    late = schemas.read_table(config.path("late_overs"), schemas.LATE_OVERS)
    out: list[str] = []
    w = out.append

    w("## 11. Exclusion log\n")
    w("Match rules are applied in order; a match is counted under the first rule it fails.\n")
    w("| stage | rule | removed |\n|---|---|---|")
    w("| parse (week 1) | none: every match and delivery in the zip is parsed | 0 |")
    for r in excl["match_rules"]:
        w(f"| overs (week 2) | match: {r['rule']} | {r['matches_removed']} matches |")
    for r in excl["innings_rules"]:
        w(f"| overs (week 2) | deliveries: {r['rule']} | {r['deliveries_removed']:,} deliveries |")
    for r in excl["chase_rules"]:
        w(f"| overs (week 2) | {r['rule']} | {r['chases']} chases |")
    k = excl["kept"]
    w(f"\n**Kept:** {k['matches']:,} matches; {k['chases_with_late_overs']:,} chases reach over 15, "
      f"giving **{k['late_over_rows']:,} late-over rows**. No late-over row is dropped.\n")
    for r in excl["match_rules"]:
        if r["match_ids"]:
            w(f"- {r['rule']}: {', '.join(r['match_ids'])}")
    w("")

    c = excl["row_checks"]
    w("## 12. Late-over table (`data/processed/late_overs.parquet`)\n")
    w("One row per started over 15-20 of a kept chase. The label `runs_in_over` = sum of `runs.total` "
      "(batter runs + wides, no-balls, byes, leg byes, penalties) until the over or the chase ends. "
      "State columns use only deliveries before the over's first ball.\n")
    w("Rules:\n")
    w(f"- Wickets fallen = dismissals. Not counted as dismissals: {', '.join(cfg['late_overs']['non_dismissal_wicket_kinds'])} "
      "(batter may return). `retired out` counts as a dismissal.")
    w("- `balls_remaining` = 6 x overs left (the over schedule). It differs from 120 - legal balls only after an "
      f"umpire miscount: {c['rows_where_120_minus_legal_differs_from_schedule']} rows.")
    w("- Bowler of the over = bowler of its first ball; previous bowler = bowler of the previous over's last ball.")
    w("- Bowler loads before each over are in `late_over_bowler_loads.parquet` (every fielding bowler who has bowled).\n")
    w("Checks (all asserted in `overs.py`; the stage fails if any breaks):\n")
    w("- no null labels; `runs_needed` > 0; `wickets_in_hand` >= 1; `balls_remaining` in 6-36; exactly one row per (match_id, over)")
    w("- row count = distinct late overs in the chase deliveries; label total = delivery runs total; "
      "`runs_scored` chains from one over to the next")
    w("- no over is bowled by the previous over's bowler\n")
    w("Counts:\n")
    w(f"- chase deliveries: {c['chase_deliveries']:,}; chase overs: {c['chase_overs']:,}; duplicate deliveries: 0; missing values: 0")
    w(f"- mid-innings overs with < 6 legal balls: {c['incomplete_overs_mid_innings']}; overs with > 6 legal balls: "
      f"{c['overs_with_extra_legal_balls']} (umpire miscounts, kept as bowled)")
    w(f"- late overs not completed because the chase ended: {c['overs_not_completed_chase_ended']}")
    w(f"- late overs with more than one bowler (mid-over replacement): {c['overs_with_more_than_one_bowler']} (kept; "
      "`n_bowlers_in_over` flags them)")
    w(f"- bowler already at the {cfg['match']['max_overs_per_bowler']}-over limit before the over: "
      f"{c['bowler_over_quota_reached_before_over']}\n")
    by_over = late.groupby("over_number")["runs_in_over"].agg(["size", "mean", "median", "std"]).round(2).reset_index()
    by_over.columns = ["over", "rows", "mean runs", "median", "sd"]
    w(md_table(by_over))
    w("\nFigure: `reports/figures/runs_in_over_by_over.png`.\n")

    w("### 12.1 Five hand-verified overs\n")
    w("Rebuilt by hand from the raw JSON in `tests/test_overs.py`; the test asserts the table matches. "
      "Check against the ESPNcricinfo scorecards of these IPL finals.\n")
    keys = pd.DataFrame(cfg["late_overs"]["verification_overs"])
    v = keys.merge(late, on=["match_id", "over"], how="left", validate="one_to_one")
    assert v["runs_in_over"].notna().all(), "a verification over is missing from the table"
    v = v.merge(m[["match_id", "event_stage"]], on="match_id")
    name = people.set_index("player_id")["display_name"]
    rows = pd.DataFrame({
        "date": v["date"].dt.date,
        "match": v["batting_team"] + " chasing v " + v["bowling_team"],
        "over": v["over_number"],
        "before the over": v["runs_scored"].astype(str) + "/" + v["wickets_fallen"].astype(str)
        + ", need " + v["runs_needed"].astype(str) + " off " + v["balls_remaining"].astype(str),
        "striker / non-striker": v["striker_id"].map(name) + " / " + v["non_striker_id"].map(name),
        "bowler (prev)": v["bowler_id"].map(name) + " (" + v["prev_bowler_id"].map(name) + ")",
        "runs in over": v["runs_in_over"],
        "legal balls": v["legal_balls_in_over"],
        "completed": v["over_completed"],
    })
    w(md_table(rows))
    w("")
    return out


def main() -> None:
    report = build_report(load_tables(), config.path("raw_zip"))
    p = config.path("data_audit")
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(report)
    log.info("wrote %s", p.relative_to(config.REPO_ROOT))


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    main()
